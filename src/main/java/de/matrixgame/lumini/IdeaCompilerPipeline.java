package de.matrixgame.lumini;
import java.text.Normalizer;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
/**
 * First deterministic LUMINI intake prototype.
 * It performs transparent keyword triage only; it does not claim to understand semantics.
 */
public final class IdeaCompilerPipeline {
    public PipelineResult process(String originalText, String source) {
        IdeaPacket packet = new IdeaPacket(originalText, source);
        List<FilterTraceEntry> trace = new ArrayList<>();
        trace.add(new FilterTraceEntry(0, "INTAKE", FilterStatus.CAPTURED,
                "Original text stored unchanged; privacy defaults to PRIVATE."));
        String unicodeNfc = Normalizer.normalize(originalText, Normalizer.Form.NFC);
        FilterStatus normalizeStatus = unicodeNfc.equals(originalText)
                ? FilterStatus.PASS : FilterStatus.REVIEW_REQUIRED;
        trace.add(new FilterTraceEntry(1, "NORMALIZE", normalizeStatus,
                unicodeNfc.equals(originalText)
                        ? "Unicode NFC check passed; source text remains unchanged."
                        : "Unicode normalization differs; proposal flagged; original text remains unchanged."));
        String lower = originalText.toLowerCase(Locale.ROOT);
        Set<PipelineRoute> routes = new LinkedHashSet<>();
        List<String> hints = new ArrayList<>();
        addHint(lower, routes, hints, PipelineRoute.CODE_MODULE,
                "java", "code", "programmier", "compile", "compiler", "software");
        addHint(lower, routes, hints, PipelineRoute.MICRO_QUEST,
                "lernen", "train", "lehr", "didakt", "quest", "motivation");
        addHint(lower, routes, hints, PipelineRoute.RESEARCH_TASK,
                "wissenschaft", "fakt", "quelle", "research", "evidenz", "daten");
        addHint(lower, routes, hints, PipelineRoute.MODEL_DRAFT,
                "kausal", "modell", "variable", "gleichung", "hypothese");
        addHint(lower, routes, hints, PipelineRoute.SIMULATION,
                "simulation", "matrixgame", "game", "spiel", "agent", "n-körper");
        if (routes.isEmpty()) routes.add(PipelineRoute.PARKED);
        String intentHint = hints.isEmpty()
                ? "No keyword signal; parked for human triage."
                : String.join("; ", hints);
        trace.add(new FilterTraceEntry(2, "INTENT_HINT", FilterStatus.REVIEW_REQUIRED,
                "Rule-based keyword hints only; human confirmation required: " + intentHint));
        trace.add(new FilterTraceEntry(3, "EPISTEMIC", FilterStatus.NOT_RUN,
                "Claim extraction and evidence review are not implemented; default status remains OPEN."));
        trace.add(new FilterTraceEntry(4, "CAUSAL", FilterStatus.NOT_RUN,
                "No causal link is inferred from co-occurrence or wording."));
        trace.add(new FilterTraceEntry(5, "FORMALIZE", FilterStatus.NOT_RUN,
                "No Model IR or executable code is generated by this intake MVP."));
        trace.add(new FilterTraceEntry(6, "ROUTE", FilterStatus.REVIEW_REQUIRED,
                "Suggested route(s) require explicit human approval: " + routes));
        trace.add(new FilterTraceEntry(7, "VERIFY", FilterStatus.NOT_RUN,
                "Build and tests are executed by the repository CI workflow, not by this intake pipeline."));
        return new PipelineResult(packet, intentHint, new ArrayList<>(routes), trace);
    }
    private static void addHint(String text, Set<PipelineRoute> routes, List<String> hints,
                                PipelineRoute route, String... keywords) {
        for (String keyword : keywords) {
            if (text.contains(keyword)) {
                routes.add(route);
                hints.add(route.name() + " (keyword='" + keyword + "')");
                return;
            }
        }
    }
}
